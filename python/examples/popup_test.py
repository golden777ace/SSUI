"""SSUI — разбор popup_test построчно.

Файл повторяет popup_test.py, но каждая строка снабжена пояснением:
что она делает, зачем нужна и как связана с остальными.

Общая идея окна: слева канвас рисует таблицу «параметр — значение».
Клик по значению открывает поле ввода, которое встаёт ровно в границы
кликнутой ячейки. Enter сохраняет, Esc или клик мимо — отменяют.

Ключевой принцип SSUI: дерево виджетов строится один раз до win.go().
После запуска дерево принадлежит рендереру, и менять его напрямую
нельзя. Всё динамическое поведение выражается через сигналы и
привязки: колбэк возвращает значение, ядро само переносит его в узел
на каждом кадре.
"""

import ssui  # Скомпилированный модуль ядра: классы W, S и функция sgnl.

CSS = """
frame { background: #141c3000; radius: 14; }
.clear { background: #00000000; }
label { color: #eef3ff; }
.head { color: #3b82f6; }
canvas { background: #0b102000; radius: 12; }

.pop { background: #0f1a30; radius: 8; color: #eef3ff; }
.pop:focus { background: #142038; }
"""
# CSS-подмножество SSUI: селекторы по типу узла (frame, label, canvas),
# по классу (.clear, .head, .pop) и по состоянию (:focus).
# Класс присваивается узлу вызовом win.cls(node, "имя").
# Восемь hex-цифр — это RRGGBBAA, последняя пара задаёт прозрачность.

OFF = -900000.0
# Координата «за пределами экрана». Ядро считает узлы левее -100000
# скрытыми и пропускает их при отрисовке (константа OFF_LIMIT в ядре).
# Это дешёвый способ спрятать попап без удаления узла из дерева.

TXT = "#eef3ff"   # Основной цвет текста фигур на канвасе.
DIM = "#94a3b8"   # Приглушённый цвет для подсказки сверху.
HOT = "#f59e0b"   # Цвет рамки активной (редактируемой) ячейки.
BOX = "#1e293b"   # Цвет фона обычной, неактивной ячейки.

CELL_W = 170.0    # Стартовая ширина ячейки значения в пикселях.
CELL_H = 34.0     # Стартовая высота ячейки значения.
COL_X = 240.0     # Отступ колонки значений от левого края канваса.
ROW_Y = 44.0      # Отступ первой строки от верха канваса.
ROW_H = 54.0      # Шаг между строками по вертикали.


def main():
    win = ssui.W("SSUI · попап ввода", 1080, 740, thm="drk",
                 glass=True, tint=0.0)
    # Создание окна. Аргументы по порядку: заголовок, ширина, высота.
    # thm — стартовая тема (wht/lit/drk/blk).
    # glass=True включает прозрачную поверхность (WS_EX_NOREDIRECTIONBITMAP
    # и DirectComposition), без неё tint не действует.
    # tint=0.9 — альфа фона окна: 1.0 непрозрачно, 0.0 полностью прозрачно.
    # Сам HWND ещё не создан: он появится только в win.go().

    rc = win.rects()
    # Контроллер доступа к геометрии. Возвращает объект Rct, который
    # хранит ссылку на таблицу прямоугольников дерева.
    # Нужен отдельный объект, а не метод окна, потому что во время
    # выполнения биндинга окно уже занято ядром: прямой вызов
    # win.rect(...) упал бы с «Already mutably borrowed».
    # Rct держит только Rc на таблицу и окно не трогает.

    fields = [
        ("Номер счётчика", "0000123456"),
        ("Коэффициент трансформации", "1"),
        ("Тариф 1, кВт·ч", "1250.40"),
        ("Тариф 2, кВт·ч", "830.15"),
        ("Адрес устройства", "16"),
    ]
    # Статические данные: подпись параметра и его стартовое значение.
    # Подписи не меняются, поэтому остаются обычным списком кортежей.

    values = [ssui.sgnl(v) for _, v in fields]
    # А вот значения меняются, поэтому каждое заворачивается в сигнал.
    # Сигнал — ячейка с отслеживанием: чтение внутри биндинга
    # регистрирует зависимость, запись помечает её грязной.
    # Благодаря этому ядро пересчитывает только затронутые биндинги.

    editing = ssui.sgnl(-1)
    # Индекс поля, которое сейчас редактируется; -1 значит «попап закрыт».
    # Это единственный источник истины о видимости попапа.

    draft = ssui.sgnl("")
    # Черновик: текущий текст в поле ввода. Поле само пишет сюда при
    # каждом нажатии клавиши (см. параметр sig= у win.tx ниже).

    log = ssui.sgnl("—")
    # Строка последнего события для нижней метки. Чисто информационная.

    cw = ssui.sgnl(CELL_W)
    # Ширина ячейки как сигнал: ползунок справа меняет её на лету,
    # и попап обязан подстроиться в тот же кадр.

    ch_ = ssui.sgnl(CELL_H)
    # Высота ячейки. Подчёркивание в имени — чтобы не столкнуться
    # с методом win.ch (checkbox).

    def shapes():
        # Биндинг канваса: вызывается ядром каждый кадр, когда изменился
        # хотя бы один прочитанный внутри сигнал. Возвращает полный
        # список фигур. Каждая фигура — кортеж
        # (вид, [аргументы], цвет, текст).

        out = [("text", [20.0, 8.0, 620.0, 26.0], DIM,
                "Кликни по значению справа, чтобы его изменить")]
        # Фигура «text»: аргументы [x, y, w, h] — прямоугольник, в который
        # вписывается строка. Координаты локальные, от левого верхнего
        # угла канваса. Это будет фигура с индексом 0.

        for i, (name, _) in enumerate(fields):
            # Обход параметров. На каждый параметр создаются ровно три
            # фигуры — этот факт используется дальше при разборе клика.

            y = ROW_Y + i * ROW_H
            # Вертикальная координата строки внутри канваса.

            hot = editing() == i
            # Редактируется ли сейчас эта строка. Вызов editing() читает
            # сигнал и одновременно подписывает биндинг shapes на него:
            # при смене editing канвас перерисуется автоматически.

            out.append(("text", [20.0, y + 6.0, 210.0, 24.0], TXT, name))
            # Подпись параметра слева. Индекс фигуры: 1 + i*3 + 0.

            out.append((
                "rect",
                [COL_X, y, cw(), ch_(), 8.0, 2.0 if hot else 0.0],
                HOT if hot else BOX,
                "",
            ))
            # Прямоугольник ячейки. Аргументы [x, y, w, h, radius, stroke].
            # stroke=0 означает заливку, stroke>0 — только контур такой
            # толщины. Активная ячейка рисуется контуром цвета HOT,
            # обычная — сплошной заливкой BOX.
            # Индекс фигуры: 1 + i*3 + 1.

            out.append((
                "text",
                [COL_X + 10.0, y + 5.0, cw() - 20.0, 24.0],
                TXT,
                values[i](),
            ))
            # Само значение поверх ячейки. values[i]() читает сигнал,
            # поэтому после сохранения текст на канвасе обновится сам.
            # Индекс фигуры: 1 + i*3 + 2.

        return out
        # Ядро принимает список, конвертирует в структуры Shape
        # и подменяет содержимое узла-канваса целиком.

    def on_shape(i):
        # Колбэк ch= у канваса. Ядро делает хит-тест по фигурам
        # в обратном порядке (верхние выигрывают) и передаёт индекс
        # найденной фигуры, либо -1 при промахе мимо всех.

        if i < 1:
            return
        # -1 — промах, 0 — фигура-подсказка сверху. Ни то, ни другое
        # редактировать нечего.

        idx = (i - 1) // 3
        # Обратный перевод индекса фигуры в индекс параметра.
        # Работает потому, что после нулевой фигуры идут ровно
        # тройки «подпись, ячейка, значение».

        if idx >= len(fields):
            return
        # Страховка на случай, если состав фигур поменяется.

        editing.st(idx)
        # Запись в сигнал. Это помечает грязными все биндинги, которые
        # читали editing: канвас перерисует рамку, попап получит
        # позицию, нижние метки обновят текст.

        win.focus(field, txt=values[idx](), sel=True)
        # Программная установка фокуса. Вызов не трогает дерево напрямую:
        # он кладёт запрос в очередь pending_focus, а рендерер разбирает
        # её в начале следующего кадра. Именно поэтому метод безопасно
        # вызывать из колбэка.
        # txt= подменяет содержимое поля текущим значением ячейки,
        # sel=True выделяет весь текст, чтобы его можно было сразу
        # заменить набором с клавиатуры.

        log.st(f"правка: {fields[idx][0]}")
        # Сообщение для информационной строки.

    def finish(code):
        # Единый обработчик завершения правки. Вызывается из трёх мест:
        # из win.keys (Enter/Esc), из кнопки «Закрыть» и из ядра при
        # клике мимо поля.
        # code: 1 — подтверждение, 0 — отмена.

        i = editing()
        # Какое поле редактировалось.

        if i >= 0 and code:
            values[i].st(draft())
            # Подтверждение: переносим черновик в постоянное значение.
            # Канвас перерисуется, потому что shapes читает values[i].

            log.st(f"сохранено: {fields[i][0]} = {draft()}")

        elif i >= 0:
            log.st("отменено")
            # Отмена: черновик просто выбрасывается, values не трогаем.

        editing.st(-1)
        # Закрываем попап: биндинг позиции увидит -1 и уведёт узел за
        # пределы экрана.

        win.focus(None)
        # Снимаем фокус, чтобы каретка не мигала в невидимом поле
        # и клавиатура не уходила в него.

    def pop_rect():
        # Биндинг позиции попапа. Возвращает кортеж (x, y, w, h)
        # в координатах окна. Ядро применяет его через set_place
        # каждый кадр, до раскладки.

        i = editing()
        if i < 0:
            return (OFF, OFF, 1.0, 1.0)
        # Попап закрыт — уводим за экран. Узел остаётся в дереве,
        # но пропускается при отрисовке. Это дешевле, чем перестраивать
        # дерево, и не требует его мутации после запуска.

        cx, cy, _, _ = rc(board)
        # Фактические координаты канваса после раскладки. Таблица
        # прямоугольников обновляется ядром сразу после layout,
        # поэтому значения всегда актуальны — в том числе после
        # изменения размера окна или сворачивания соседних панелей.
        # Без этого пришлось бы вписывать смещения константами,
        # и попап разъезжался бы при любом ресайзе.

        return (cx + COL_X, cy + ROW_Y + i * ROW_H, cw(), ch_())
        # Локальные координаты ячейки переводятся в оконные простым
        # сложением. Размер берётся из тех же сигналов, что и у фигуры,
        # поэтому совпадение с ячейкой попиксельное.

    with win.bx(pr=win.rt(), ax="h", pd=14.0, gp=14.0) as root:
        # Корневой контейнер. bx возвращает контекст: внутри with все
        # последующие виджеты автоматически становятся его детьми.
        # pr=win.rt() — явное указание родителя (корня окна), нужно
        # потому что стек контекстов на этом уровне ещё пуст.
        # ax="h" — горизонтальная раскладка, дети идут слева направо.
        # pd — внутренний отступ, gp — зазор между детьми.

        win.cls(root, "clear")
        # Присваиваем класс, чтобы CSS-правило .clear убрало фон:
        # иначе панель нарисовала бы свой прямоугольник поверх окна.

        with win.bx(pd=14.0, gp=10.0):
            # Левая колонка. Без ax= раскладка вертикальная (по умолчанию).
            # Без w= колонка растянется на всё оставшееся место.

            t = win.lb("Редактор параметров", h=30.0)
            # Обычная метка. h= фиксирует высоту строки.

            win.cls(t, "head")
            # Класс .head красит заголовок в акцентный цвет.

            board = win.cv([], bind=shapes, ch=on_shape, h=360.0)
            # Канвас. Первый аргумент — статический список фигур;
            # он пуст, потому что содержимое даёт bind=.
            # bind= вызывается каждый кадр при изменении зависимостей.
            # ch= получает индекс фигуры под курсором при клике.
            # Возвращённый узел сохраняем: он понадобится в pop_rect
            # для запроса фактических координат.

            win.sep()
            # Горизонтальный разделитель.

            win.lb(bind=lambda: f"Событие: {log()}", h=28.0)
            # Метка с динамическим текстом. bind= читает log(),
            # значит перерисуется при каждой записи в этот сигнал.

            win.lb(bind=lambda: (
                "Попап закрыт" if editing() < 0
                else f"Открыт попап поля #{editing()}"
            ), h=26.0)
            # Состояние попапа. Зависит от editing.

            win.lb(bind=lambda: (
                "Канвас: x={:.0f} y={:.0f} w={:.0f} h={:.0f}"
                .format(*rc(board))
            ), h=26.0)
            # Диагностика: показывает, что таблица прямоугольников
            # действительно живая. Потяни за край окна — числа поедут.

        with win.bx(pd=14.0, gp=8.0, w=320.0):
            # Правая колонка. w=320 фиксирует ширину, поэтому вся
            # свободная ширина достаётся левой колонке.

            t2 = win.lb("Размер ячейки", h=30.0)
            win.cls(t2, "head")
            win.sep()

            win.lb(bind=lambda: f"Ширина ячейки: {cw():.0f}", h=24.0)
            # Подпись над ползунком, показывает текущее значение.

            win.sl(0.35, ch=lambda v: cw.st(90.0 + v * 230.0), h=32.0)
            # Ползунок. Первый аргумент — стартовая позиция 0..1.
            # ch= получает новую позицию и пересчитывает её в пиксели.
            # Запись в cw перерисует и фигуру ячейки, и попап.

            win.lb(bind=lambda: f"Высота ячейки: {ch_():.0f}", h=24.0)
            win.sl(0.25, ch=lambda v: ch_.st(26.0 + v * 32.0), h=32.0)
            # То же для высоты.

            win.lb("Попап повторяет размер ячейки один в один — "
                   "меняй ползунки при открытом попапе.",
                   h=60.0, wrap=True)
            # wrap=True включает перенос длинного текста по словам.

            win.sep()
            win.lb("Enter сохраняет. Esc или клик мимо — отмена.",
                   h=44.0, wrap=True)

            win.bt("Закрыть без сохранения", h=42.0, clk=lambda: finish(0))
            # Кнопка. clk= вызывается без аргументов при нажатии.
            # finish(0) — тот же путь отмены, что у Esc.

            win.sep()
            win.lb("Текущие значения:", h=26.0)

            for i in range(len(fields)):
                win.lb(
                    bind=(lambda k: lambda: f"{fields[k][0]}: {values[k]()}")(i),
                    h=38.0, wrap=True,
                )
                # Список текущих значений. Двойная лямбда фиксирует i
                # в замыкании: без неё все метки читали бы последнее
                # значение переменной цикла — классическая ловушка
                # позднего связывания в Python.

    field = win.tx("", sig=draft, pr=win.rt(), h=CELL_H)
    # Сам попап. Это обычное однострочное поле ввода, но его родитель —
    # корень окна, а не какая-либо панель. Поэтому оно не участвует
    # в раскладке колонок и может быть размещено где угодно.
    # sig=draft связывает поле с сигналом: при каждом нажатии клавиши
    # ядро пишет текущий текст в draft.
    # Обёртки-контейнера сознательно нет: любая обёртка добавила бы
    # свои отступы и радиус, и границы перестали бы совпадать с ячейкой.

    win.cls(field, "pop")
    # Класс для оформления. Правила .pop и .pop:focus в CSS задают фон
    # в обычном состоянии и в фокусе — так же настраивается любой
    # другой tx в приложении.

    win.pl(field, x=OFF, y=OFF, w=1.0, h=1.0)
    # Стартовое абсолютное размещение за экраном. Нужно именно здесь:
    # биндинги впервые выполняются только после первого кадра, и без
    # этой строки попап на мгновение раскрылся бы в обычном потоке
    # раскладки и занял часть окна.

    win.bindp(field, pop_rect)
    # Привязка позиции к колбэку. С этого момента положение и размер
    # узла целиком определяются pop_rect и обновляются каждый кадр.

    win.dep(field, 500)
    # Глубина по оси z. Большое значение гарантирует, что попап
    # рисуется поверх соседей по родителю, то есть поверх всего окна.

    win.keys(field, finish)
    # Реакция на клавиши в поле: ядро вызывает колбэк с 1 при Enter
    # и с 0 при Esc, после чего сбрасывает фокус.
    # Тот же колбэк ядро вызывает с 0, когда пользователь щёлкает
    # мимо сфокусированного поля — эквивалент FocusOut.

    win.css(CSS)
    # Применение стилей. Вызывается обязательно после того, как всё
    # дерево построено: каскад раскладывается по существующим узлам,
    # и узлы, созданные позже, стилей не получат.

    win.go()
    # Создание HWND, инициализация Direct3D/Direct2D и запуск цикла
    # сообщений. Вызов блокирующий: он вернётся только когда это
    # окно — главное — будет закрыто.
    # Дочерние окна, созданные через win.subwin(...), живут в этом же
    # цикле и его не блокируют.


if __name__ == "__main__":
    main()
    # Стандартная точка входа: тело выполняется только при прямом
    # запуске файла, а не при импорте.